/**
 * 把三十八个图形注册进 Obsidian 的图标库，并登记卸载时撤走它们。
 *
 * 必须在任何一个用到它们的界面画出来之前调用；ribbon 模块在装配时第一件事就是调它。
 * addIcon 幂等（同名后注册的覆盖先注册的），热重载不会留下两份；
 * 但图标库是 Obsidian 全局的，插件卸载时它不会自己清——不撤走的话，
 * ziminOS 卸载后那三十八个名字仍然留在别人的命名空间里。这是本模块唯一的全局副作用，
 * 所以它也是本模块唯一需要手写清理的地方。
 */
export function registerZiminosIcons(plugin: Plugin): void {
    for (const [name, paths] of Object.entries(ARTWORK)) {
        addIcon(name, wrap(paths));
        plugin.register(() => removeIcon(name));
    }
}

/**
 * 把一组 24 格坐标系里的 path 包成 addIcon 认得的内容。
 *
 * 外层那个 `0 0 100 100` 的 svg 由 Obsidian 建，这里补一层自带 viewBox 的内层 svg，
 * 让 24 格整个铺满 100 格。属性写在内层 svg 上、由 path 继承，
 * 于是主题给外层 `.svg-icon` 设的描边宽度管不到我们——那个值是按它自己的坐标系算的。
 */
function wrap(paths: readonly string[]): string {
    const body = paths.map((d) => `<path d="${d}"/>`).join('');

    return (
        `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}"` +
        ` width="${BOX}" height="${BOX}" fill="none" stroke="currentColor"` +
        ` stroke-linecap="round" stroke-linejoin="round" style="stroke-width:${STROKE}">` +
        `${body}</svg>`
    );
}
